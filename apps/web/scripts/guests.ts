/**
 * Guest list import: parsing and validation of the wedding spreadsheet's CSV
 * exports, invite-code generation and the SQL upserts for D1. Ported from the
 * 2022 CLI (`wedding-manager invite:update` and `invite:gen-codes`); the
 * command-line wrapper is import-guests.ts.
 */
import { sql } from "drizzle-orm"
import { drizzle } from "drizzle-orm/sqlite-proxy"
import { nanoid } from "nanoid"
import Papa from "papaparse"
import { z } from "zod"
import { type Itype, invitations, invitees } from "../src/server/db/schema.ts"

export type { Itype }

export interface Email {
  name: string
  email: string
  uniquePartyName?: string
}

export interface Party {
  code: string
  /** True when the CSV had no code and one was generated. */
  generated: boolean
  uniquePartyName: string
  partyName: string
  numGuests: number
  knownGuests: string[]
  itype: Itype
  emails: Email[]
}

export interface Invitee {
  /** Lower-cased, as the `invitees` primary key. */
  email: string
  name: string
  code: string
}

export interface ImportPlan {
  parties: Party[]
  invitees: Invitee[]
  /** Emails without a (known) party: not imported, as in 2022. */
  unmatchedEmails: Email[]
  /** The parties CSV with generated codes filled in. */
  partiesCsvWithCodes: string
}

export class ImportError extends Error {}

const MaxNumGuests = 11

// ---------------------------------------------------------------------------
// Invitation codes

/**
 * The 2022 codes were generated by the (now deprecated) `shortid` package:
 * 7-14 characters from `0-9a-zA-Z_-`. nanoid's default alphabet is the same
 * set of characters, so new codes are indistinguishable from the old ones.
 */
const CodeLength = 9

/** Matches any code `shortid.isValid` accepted: 6+ chars of [0-9a-zA-Z_-]. */
const CodePattern = /^[0-9a-zA-Z_-]{6,}$/

export function generateCode(): string {
  return nanoid(CodeLength)
}

export function isValidCode(value: unknown): value is string {
  return typeof value === "string" && CodePattern.test(value)
}

/** A fresh code not in `taken` (which it is then added to). */
export function generateUniqueCode(
  taken: Set<string>,
  generate: () => string = generateCode
): string {
  for (let attempt = 0; attempt < 100; attempt++) {
    const code = generate()
    if (!taken.has(code)) {
      taken.add(code)
      return code
    }
  }
  throw new ImportError("could not generate a unique invitation code")
}

// ---------------------------------------------------------------------------
// Parsing and validation

export function yn(value: string | undefined): boolean {
  return value !== undefined && /^(?:y|yes)$/i.test(value)
}

export function parseItype(
  preEvents: boolean,
  sangeet: boolean,
  ceremony: boolean
): Itype | undefined {
  if (preEvents && sangeet && ceremony) {
    return "a"
  } else if (preEvents && sangeet && !ceremony) {
    return "psr"
  } else if (preEvents && !sangeet && !ceremony) {
    return "pr"
  } else if (!preEvents && sangeet && ceremony) {
    return "w"
  } else if (!preEvents && !sangeet && ceremony) {
    return "ow"
  } else if (!preEvents && sangeet && !ceremony) {
    return "sr"
  } else if (!preEvents && !sangeet && !ceremony) {
    return "r"
  } else {
    return undefined
  }
}

const emailCsvSchema = z.object({
  name: z.string().trim().min(1),
  email: z.string().trim().pipe(z.email()),
  cleanedName: z.string().trim().optional(),
  skip: z.enum(["y", ""]).optional(),
  uniquePartyName: z.string().trim().optional(),
})

const yesNo = z.enum(["y", "n"])

const partyCsvSchema = z.object({
  // Blank codes are generated.
  code: z
    .string()
    .trim()
    .default("")
    .refine((code) => code === "" || isValidCode(code), {
      message: "is not a valid invitation code",
    }),
  uniquePartyName: z.string().trim().min(1),
  partyName: z.string().trim().min(1),
  preEvents: yesNo,
  ceremony: yesNo,
  sangeet: yesNo,
  // Same bounds as the invitations table (0 < num_guests < 15).
  numGuests: z.coerce.number().int().min(1).max(14),
})

type Row = Record<string, string | undefined>

function parseCsv(text: string): {
  rows: Row[]
  fields: string[]
  linebreak: string
} {
  const result = Papa.parse<Row>(text.replace(/^\uFEFF/, ""), {
    header: true,
    skipEmptyLines: true,
  })
  if (result.errors.length > 0) {
    const e = result.errors[0]
    throw new ImportError(`CSV row ${(e.row ?? 0) + 2}: ${e.message}`)
  }
  return {
    rows: result.data,
    fields: result.meta.fields ?? [],
    linebreak: result.meta.linebreak || "\n",
  }
}

function validateRows<T>(file: string, rows: Row[], schema: z.ZodType<T>): T[] {
  const problems: string[] = []
  const parsed = rows.map((row, i) => {
    const result = schema.safeParse(row)
    if (result.success) return result.data
    for (const issue of result.error.issues) {
      // Row 1 is the header.
      problems.push(
        `${file} row ${i + 2}: ${issue.path.join(".") || "row"} ${issue.message}`
      )
    }
    return undefined as T
  })
  if (problems.length > 0) throw new ImportError(problems.join("\n"))
  return parsed
}

/** Validated emails, minus the ones marked `skip` (duplicates). */
export function parseEmails(text: string): Email[] {
  const emails = validateRows("emails", parseCsv(text).rows, emailCsvSchema)
    // Skip emails manually marked for skipping (duplicates)
    .filter((email) => !yn(email.skip))
    .map((email) => ({
      name: (email.cleanedName || email.name).trim(),
      email: email.email.trim(),
      uniquePartyName: email.uniquePartyName || undefined,
    }))

  // Check for and alert on duplicate emails (invitees are keyed by the
  // lower-cased address).
  const counts = new Map<string, number>()
  for (const { email } of emails) {
    const key = email.toLowerCase()
    counts.set(key, (counts.get(key) ?? 0) + 1)
  }
  const duplicates = [...counts].filter(([, n]) => n > 1).map(([e]) => e)
  if (duplicates.length > 0) {
    throw new ImportError(`duplicate emails detected: ${duplicates}`)
  }
  return emails
}

function duplicatesOf(values: string[]): string[] {
  const seen = new Set<string>()
  const dupes = new Set<string>()
  for (const v of values) (seen.has(v) ? dupes : seen).add(v)
  return [...dupes]
}

/**
 * Everything the import will write. `existingCodes` (the codes already in
 * D1) are avoided when generating codes for parties with a blank `code`.
 */
export function planImport(options: {
  partiesCsv: string
  emailsCsv: string
  existingCodes?: Iterable<string>
  generate?: () => string
}): ImportPlan {
  const emails = parseEmails(options.emailsCsv)
  const emailsByUniquePartyName = Map.groupBy(
    emails,
    (email) => email.uniquePartyName
  )

  const { rows, fields, linebreak } = parseCsv(options.partiesCsv)
  const validated = validateRows("parties", rows, partyCsvSchema)

  const problems: string[] = []
  const csvCodes = validated.map((p) => p.code).filter(Boolean)
  const duplicateCodes = duplicatesOf(csvCodes)
  if (duplicateCodes.length > 0) {
    problems.push(`duplicate codes: ${duplicateCodes}`)
  }
  const duplicateNames = duplicatesOf(validated.map((p) => p.uniquePartyName))
  if (duplicateNames.length > 0) {
    problems.push(`duplicate uniquePartyName values: ${duplicateNames}`)
  }

  const taken = new Set([...(options.existingCodes ?? []), ...csvCodes])
  const parties: Party[] = validated.map((row, i) => {
    const knownGuests = Array.from({ length: MaxNumGuests }, (_, g) =>
      (rows[i][`knownGuest${g + 1}`] ?? "").trim()
    ).filter((guest) => !!guest)
    const preEvents = yn(row.preEvents)
    const sangeet = yn(row.sangeet)
    const ceremony = yn(row.ceremony)
    const itype = parseItype(preEvents, sangeet, ceremony)
    if (!itype) {
      problems.push(
        `Could not generate itype for invitation ${row.uniquePartyName}: preEvents = ${preEvents},` +
          ` sangeet = ${sangeet}, ceremony = ${ceremony}`
      )
    }
    const generated = row.code === ""
    return {
      code: generated ? generateUniqueCode(taken, options.generate) : row.code,
      generated,
      uniquePartyName: row.uniquePartyName,
      partyName: row.partyName,
      numGuests: row.numGuests,
      knownGuests,
      itype: itype ?? "r",
      emails: emailsByUniquePartyName.get(row.uniquePartyName) ?? [],
    }
  })

  // Validation for parties: known guest count is valid
  const invalidParties = parties.filter(
    (party) => party.numGuests < party.knownGuests.length
  )
  if (invalidParties.length > 0) {
    problems.push(
      `Invalid guest records (known guests exceed numGuests): ${invalidParties.map(
        (party) => party.uniquePartyName
      )}`
    )
  }
  if (problems.length > 0) throw new ImportError(problems.join("\n"))

  const partyNames = new Set(parties.map((p) => p.uniquePartyName))
  return {
    parties,
    invitees: parties.flatMap((party) =>
      party.emails.map((email) => ({
        email: email.email.toLowerCase(),
        name: email.name,
        code: party.code,
      }))
    ),
    unmatchedEmails: emails.filter(
      (e) => !e.uniquePartyName || !partyNames.has(e.uniquePartyName)
    ),
    // Same columns and line breaks as the input.
    partiesCsvWithCodes:
      Papa.unparse(
        rows.map((row, i) => ({ ...row, code: parties[i].code })),
        {
          columns: fields.includes("code") ? fields : ["code", ...fields],
          newline: linebreak,
        }
      ) + linebreak,
  }
}

// ---------------------------------------------------------------------------
// SQL

export function sqlString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function sqlLiteral(value: unknown): string {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "string") return sqlString(value)
  if (typeof value === "boolean") return value ? "1" : "0"
  if (typeof value === "number" && Number.isSafeInteger(value)) {
    return String(value)
  }
  throw new ImportError(`unexpected SQL parameter: ${JSON.stringify(value)}`)
}

/**
 * A Drizzle query as one SQL statement with its parameters inlined, for a
 * reviewable file. Drizzle quotes identifiers and passes every value as a
 * `?` parameter, so each `?` in its SQL is a placeholder.
 */
export function inlineSql(query: { sql: string; params: unknown[] }): string {
  let i = 0
  const text = query.sql.replace(/\?/g, () => sqlLiteral(query.params[i++]))
  if (i !== query.params.length) {
    throw new ImportError(`parameter count mismatch in: ${query.sql}`)
  }
  return `${text};`
}

// Builds queries only; never executed.
const queryBuilder = drizzle(async () => ({ rows: [] }))

/**
 * Upserts for `wrangler d1 execute --file`. Like the 2022 Firestore
 * `set(..., { merge: true })`: only the imported columns are written, so an
 * invitation keeps its latest RSVP, view times and `inactive` flag, and an
 * invitee keeps `inactive`. Invitations come first (invitees reference them).
 */
export function toSql(plan: Pick<ImportPlan, "parties" | "invitees">): string {
  const lines = [
    `-- Guest import: ${plan.parties.length} invitations, ${plan.invitees.length} invitees.`,
  ]
  for (const p of plan.parties) {
    const query = queryBuilder
      .insert(invitations)
      .values({
        code: p.code,
        partyName: p.partyName,
        numGuests: p.numGuests,
        knownGuests: p.knownGuests,
        itype: p.itype,
      })
      .onConflictDoUpdate({
        target: invitations.code,
        set: {
          partyName: sql`excluded.party_name`,
          numGuests: sql`excluded.num_guests`,
          knownGuests: sql`excluded.known_guests`,
          itype: sql`excluded.itype`,
        },
      })
    lines.push(inlineSql(query.toSQL()))
  }
  for (const i of plan.invitees) {
    const query = queryBuilder
      .insert(invitees)
      .values({ email: i.email, name: i.name, code: i.code })
      .onConflictDoUpdate({
        target: invitees.email,
        set: { name: sql`excluded.name`, code: sql`excluded.code` },
      })
    lines.push(inlineSql(query.toSQL()))
  }
  return `${lines.join("\n")}\n`
}

// ---------------------------------------------------------------------------
// Dry-run summary

export function describePlan(
  plan: ImportPlan,
  existing: { codes: Set<string>; emails: Set<string> }
): string {
  const created = plan.parties.filter((p) => !existing.codes.has(p.code))
  const updated = plan.parties.filter((p) => existing.codes.has(p.code))
  const newInvitees = plan.invitees.filter((i) => !existing.emails.has(i.email))
  const oldInvitees = plan.invitees.filter((i) => existing.emails.has(i.email))
  const generated = plan.parties.filter((p) => p.generated)
  const party = (p: Party) =>
    `${p.code}  ${p.partyName} (${p.numGuests} guest${p.numGuests === 1 ? "" : "s"}, itype ${p.itype})`
  const invitee = (i: Invitee) => `${i.email} -> ${i.code} (${i.name})`
  const section = <T>(title: string, items: T[], fmt: (t: T) => string) =>
    items.length > 0 ? [`${title}:`, ...items.map((t) => `  ${fmt(t)}`)] : []

  return [
    `Invitations: ${plan.parties.length} (${created.length} new, ${updated.length} updated, ${generated.length} new codes)`,
    `Invitees: ${plan.invitees.length} (${newInvitees.length} new, ${oldInvitees.length} updated)`,
    ...section(
      "New codes",
      generated,
      (p) => `${p.uniquePartyName} -> ${p.code}`
    ),
    ...section("New invitations", created, party),
    ...section("Updated invitations", updated, party),
    ...section("New invitees", newInvitees, invitee),
    ...section("Updated invitees", oldInvitees, invitee),
    ...section(
      "Skipped emails (no matching party)",
      plan.unmatchedEmails,
      (e) => `${e.email} (${e.uniquePartyName || "no party"})`
    ),
  ].join("\n")
}
